# ---------------------------------------------
# Rebuilt dense() from binary
# ---------------------------------------------

def dense(x, W, B):
    return [
        B[i] + sum(x[j] * W[i][j] for j in range(8))
        for i in range(8)
    ]


# main() function logic:
#
# if (value < 0)
#     value *= 2;
#

def activate(x):
    return [
        If(v < 0, v * 2, v)
        for v in x
    ]


# ---------------------------------------------
# Finding variables
# ---------------------------------------------

x = [Int(f"x{i}") for i in range(8)]

solver = Solver()


# Entries come from sscanf("%d ...")

for v in x:
    solver.add(v >= 0)
    solver.add(v <= 255)


# ---------------------------------------------
# LAYER 0
# ---------------------------------------------

l0_raw = dense(x, L0_W, L0_B)
l0 = activate(l0_raw)


# ---------------------------------------------
# LAYER 1
# ---------------------------------------------

l1_raw = dense(l0, L1_W, L1_B)
l1 = activate(l1_raw)


# ---------------------------------------------
# LAYER 2
# ---------------------------------------------

output = dense(l1, L2_W, L2_B)


# ECHO_S Validation:
#
# if (v60[i] != ECHO_S[i])
#     valid = 0;
#
for i in range(8):
    solver.add(output[i] == ECHO_S[i])


# ---------------------------------------------
# SOLVE
# ---------------------------------------------

if solver.check() == sat:

    model = solver.model()

    solution = [
        model.evaluate(x[i]).as_long()
        for i in range(8)
    ]

    print("[+] First Mark:")
    print(solution)

    print("\n[+] Cchallenge input:")
    print(" ".join(map(str, solution)))

    print("\n[+] ASCII:")

    ascii_value = "".join(
        chr(v) if 32 <= v <= 126 else "."
        for v in solution
    )

    print(ascii_value)

else:
    print("[-] Solution not found")